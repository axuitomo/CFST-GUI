export type ColoCountryFormat = "name" | "code";

const COLO_COUNTRY_FORMAT_STORAGE_KEY = "cfst-results-colo-country-format";

export function coloCountryCode(colo: string | undefined | null): string {
  return COLO_COUNTRY_CODES[(colo || "").trim().toUpperCase()] || "";
}

export function formatColoCountry(colo: string | undefined | null, format: ColoCountryFormat): string {
  const code = coloCountryCode(colo);
  if (!code) {
    return "-";
  }
  return format === "code" ? code : COUNTRY_NAMES[code] || code;
}

export function readColoCountryFormat(): ColoCountryFormat {
  try {
    return window.localStorage.getItem(COLO_COUNTRY_FORMAT_STORAGE_KEY) === "code" ? "code" : "name";
  } catch {
    return "name";
  }
}

export function saveColoCountryFormat(format: ColoCountryFormat) {
  try {
    window.localStorage.setItem(COLO_COUNTRY_FORMAT_STORAGE_KEY, format);
  } catch {
    // 隐私模式或存储被禁用时只保留本次会话的选择。
  }
}
